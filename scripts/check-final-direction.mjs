import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import sharp from 'sharp';
await mkdir('qa/final',{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1050},reducedMotion:'no-preference',colorScheme:'light'});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5175/',{waitUntil:'networkidle'});
await page.evaluate(()=>document.fonts.ready);
const floats=page.locator('.memory-float');
const before=await floats.evaluateAll(es=>es.map(e=>({name:getComputedStyle(e).animationName,duration:getComputedStyle(e).animationDuration,transform:getComputedStyle(e).transform})));
await page.waitForTimeout(1100);
const after=await floats.evaluateAll(es=>es.map(e=>getComputedStyle(e).transform));
assert.ok(before.every((item,i)=>item.transform!==after[i]),'All photos move while idle');
assert.equal(new Set(before.map(item=>item.name)).size,3);
assert.equal(new Set(before.map(item=>item.duration)).size,3);
assert.equal(await page.locator('.world-hero-copy').evaluate(e=>getComputedStyle(e).animationName),'none');
assert.match(await page.locator('.hero-sky-image').evaluate(e=>getComputedStyle(e).backgroundImage),/dianita-bg/);
const photoBox = await page.locator('.hero-postcard-paris .postcard').boundingBox();
await page.mouse.move(photoBox.x + photoBox.width / 2, photoBox.y + photoBox.height / 2);
await page.waitForFunction(() => getComputedStyle(document.querySelector('.hero-postcard-paris .memory-float')).animationPlayState === 'paused');
assert.equal(await page.locator('.hero-postcard-paris .memory-float').evaluate(e=>getComputedStyle(e).animationPlayState),'paused');
assert.equal(await page.locator('.hero-postcard-paris .postcard').evaluate(e=>getComputedStyle(e).rotate),'0deg');
await page.getByRole('button',{name:'Pausar animaciones',exact:true}).click();
assert.equal(await page.locator('html').getAttribute('data-motion-paused'),'true');
assert.equal(await page.locator('.hero-sky-image').evaluate(e=>getComputedStyle(e).animationPlayState),'paused');
await page.getByRole('button',{name:'Reanudar animaciones',exact:true}).click();
await page.mouse.move(720,30);
await page.screenshot({path:'qa/final/desktop-hero.png'});
await page.emulateMedia({reducedMotion:'reduce'});
for(const selector of ['.memory-float','.hero-sky-image','.marquee-track','.ambient-heart'])assert.equal(await page.locator(selector).first().evaluate(e=>getComputedStyle(e).animationName),'none');
await page.setViewportSize({width:390,height:900});await page.goto('http://127.0.0.1:5175/',{waitUntil:'networkidle'});
await page.screenshot({path:'qa/final/mobile-hero.png'});
await page.evaluate(()=>scrollTo(0,650));await page.screenshot({path:'qa/final/mobile-collage.png'});
await page.emulateMedia({reducedMotion:'no-preference'});await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
assert.notEqual(await page.locator('.memory-float').first().evaluate(e=>getComputedStyle(e).animationName),'none');
await page.emulateMedia({reducedMotion:'reduce'});
await page.locator('#diario').scrollIntoViewIfNeeded();
const diary=await page.locator('.diary-collage').evaluate(e=>({width:e.clientWidth,scroll:e.scrollWidth}));assert.ok(diary.scroll>diary.width);
await page.locator('.diary-collage').evaluate(e=>e.scrollLeft=250);assert.ok(await page.locator('.diary-collage').evaluate(e=>e.scrollLeft)>0);
await page.locator('.ocean-cruises').scrollIntoViewIfNeeded();await page.screenshot({path:'qa/final/mobile-cruises.png'});
await page.locator('#contacto').scrollIntoViewIfNeeded();await page.screenshot({path:'qa/final/mobile-form.png'});
await page.setViewportSize({width:1024,height:900});await page.goto('http://127.0.0.1:5175/',{waitUntil:'networkidle'});await page.screenshot({path:'qa/final/tablet-hero.png'});
await page.setViewportSize({width:1440,height:1000});await page.goto('http://127.0.0.1:5175/',{waitUntil:'networkidle'});
await page.getByRole('button',{name:'Activar modo oscuro'}).click();await page.screenshot({path:'qa/final/dark-hero.png'});
assert.deepEqual(errors,[]);
await writeFile('qa/final/motion-checks.json',JSON.stringify({idleAnimations:before,diary,runtimeErrors:errors,checks:['independent idle motion','hover pause and straightening','steady headline','supplied sky','global motion pause/resume','reduced motion','mobile floating','horizontal mobile diary','tablet','dark mode']},null,2));
await browser.close();
await sharp('qa/redesign/desktop.png').resize({width:700}).toFile('qa/final/page-review.png');
console.log('Final motion and layout checks passed.');
